"""
Pydantic v2 schemas for alerts and officer approval workflow.

AlertOut         — serialised alert record returned by the API
ApprovalRequest  — request body for POST /recommendations/{id}/approve
ApprovalOut      — serialised approval record returned by the API
"""

from __future__ import annotations

from datetime import datetime
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, Field


class AlertOut(BaseModel):
    """
    Represents a single alert drafted by the co-pilot and stored in the
    ``alerts`` table.

    Status lifecycle: draft → approved → published | rejected
    """

    id: UUID = Field(..., description="Unique alert record identifier")
    recommendation_id: UUID = Field(
        ..., description="FK to the recommendation that produced this alert"
    )
    channel: str = Field(
        ...,
        description="Publication channel: 'vms', 'radio', or 'social'",
    )
    draft_text: str = Field(
        ...,
        description="Draft message text as generated by the co-pilot",
    )
    status: str = Field(
        ...,
        description="Alert lifecycle status: 'draft', 'approved', 'published', 'rejected'",
    )
    created_at: datetime = Field(..., description="Timestamp when the alert record was created")

    model_config = {"from_attributes": True, "populate_by_name": True}


class ApprovalRequest(BaseModel):
    """
    Request body submitted when an officer approves or rejects a recommendation.

    The ``action`` field is not included here because it is expressed via the
    HTTP method / path (e.g. POST .../approve  vs  POST .../reject).  The
    endpoint handler is responsible for setting the action string before
    persisting the approval record.
    """

    officer_id: str = Field(
        ...,
        min_length=1,
        description="Badge number or user ID of the approving / rejecting officer",
    )
    note: str | None = Field(
        default=None,
        max_length=1000,
        description="Optional free-text justification or modification note",
    )

    model_config = {"populate_by_name": True}


class ApprovalOut(BaseModel):
    """
    Serialised approval record as stored in the ``approvals`` table.

    ``action`` will be one of: 'approved', 'rejected', 'modified'.
    """

    id: UUID = Field(..., description="Unique approval record identifier")
    recommendation_id: UUID = Field(
        ..., description="FK to the recommendation that was acted upon"
    )
    officer_id: str = Field(
        ..., description="Badge number or user ID of the officer who took the action"
    )
    action: Literal["approved", "rejected", "modified"] = Field(
        ..., description="The decision taken by the officer"
    )
    note: str | None = Field(
        default=None,
        description="Optional officer note explaining the decision or requested modification",
    )
    actioned_at: datetime = Field(
        ..., description="Timestamp when the approval / rejection was recorded"
    )

    model_config = {"from_attributes": True, "populate_by_name": True}
